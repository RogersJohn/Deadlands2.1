/**
 * AI Commentary Panel (PR 5.0)
 *
 * CRITICAL INVARIANT: AI is commentary, not control.
 *
 * This panel displays read-only AI commentary. It has NO authority
 * and CANNOT affect system behavior.
 *
 * KILL CRITERIA (any violation fails PR 5.0):
 * - Panel is visible by default
 * - Panel contains interactive elements (buttons, links that act)
 * - Panel output influences system behavior
 * - Panel persists any data as authority
 * - Panel feeds back into validation or resolution
 *
 * The panel MUST be:
 * - Hidden by default
 * - Explicitly user-opened
 * - Clearly labeled "Advisory / Non-Authoritative"
 * - Visually subordinate to validation results and GM override controls
 * - Completely non-interactive (read-only text display)
 */

