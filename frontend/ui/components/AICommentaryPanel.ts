/**
 * Panel header text - clearly labeled as advisory
 */
export const PANEL_HEADER = 'AI Commentary (Advisory Only)';

/**
 * Panel disclaimer - emphasizes non-authority
 */
export const PANEL_DISCLAIMER =
  'This commentary is generated by AI and has NO authority over game state. ' +
  'It is purely informational and advisory. The GM and rules engine are the sole authorities.';

/**
 * Render the panel to HTML string (for display)
 *
 * CRITICAL: This is READ-ONLY HTML.
 * - No interactive elements (no buttons, forms, links that act)
 * - No event handlers that modify state
 * - Pure text display only
 *
 * @param state - Current panel state
 * @returns HTML string for display (read-only)
 */
export function renderPanelHTML(state: AICommentaryPanelState): string {
  if (!state.isVisible) {
    return ''; // Hidden panel renders nothing
  }

  const lines: string[] = [];

  // Panel container with advisory styling
  lines.push('<aside class="ai-commentary-panel" aria-label="AI Commentary (Advisory)"');
  lines.push('  role="complementary"');
  lines.push('  data-authority="none"');
  lines.push('  style="opacity: 0.8; border-left: 3px solid #888; padding-left: 1em;">');

  // Header with clear advisory label
  lines.push(`  <header style="font-size: 0.9em; color: #666;">`);
  lines.push(`    <strong>${escapeHTML(PANEL_HEADER)}</strong>`);
  lines.push('  </header>');

  // Disclaimer
  lines.push('  <p style="font-size: 0.8em; color: #888; font-style: italic;">');
  lines.push(`    ${escapeHTML(PANEL_DISCLAIMER)}`);
  lines.push('  </p>');

  // Content area
  lines.push('  <div class="ai-commentary-content">');

  if (state.isLoading) {
    lines.push('    <p style="color: #666;">Loading commentary...</p>');
  } else if (state.error) {
    lines.push(`    <p style="color: #c00;">Commentary unavailable: ${escapeHTML(state.error)}</p>`);
    lines.push('    <p style="font-size: 0.8em; color: #888;">System behavior is unchanged.</p>');
  } else if (state.commentary) {
    // Render commentary as pre-formatted text (markdown display would be here)
    lines.push(`    <div class="ai-commentary-text" style="white-space: pre-wrap;">`);
    lines.push(`      ${escapeHTML(state.commentary)}`);
    lines.push('    </div>');
  } else {
    lines.push('    <p style="color: #888;">No commentary requested.</p>');
  }

  lines.push('  </div>');

  // Footer with timestamp
  if (state.lastFetchedAt) {
    const timestamp = new Date(state.lastFetchedAt).toLocaleTimeString();
    lines.push(`  <footer style="font-size: 0.7em; color: #aaa; margin-top: 1em;">`);
    lines.push(`    Generated at: ${escapeHTML(timestamp)} (advisory snapshot)`);
    lines.push('  </footer>');
  }

  lines.push('</aside>');

  return lines.join('\n');
}

/**
 * Escape HTML to prevent XSS
 *
 * CRITICAL: All user-visible text must be escaped.
 */
function escapeHTML(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

// ============================================================================
// VALIDATION (ENSURES PANEL STAYS READ-ONLY)
// ============================================================================

/**
 * Validate that panel state has no authority indicators
 *
 * This function can be used by tests to verify the panel
 * has not accidentally gained authority.
 */
export function validateNoAuthority(state: AICommentaryPanelState): boolean {
  // Panel state should have no fields that could indicate authority
  const stateKeys = Object.keys(state);
  const forbiddenKeys = [
    'effectsToApply',
    'overrideRequest',
    'validationOverride',
    'intentModification',
    'pendingAction',
    'actionQueue',
  ];

  for (const key of stateKeys) {
    if (forbiddenKeys.includes(key)) {
      return false;
    }
  }

  return true;
}

