// ============================================================================
// PANEL STATE (UI-ONLY, NON-AUTHORITATIVE)
// ============================================================================

/**
 * AICommentaryPanelState - state of the AI commentary panel
 *
 * This state is UI-ONLY. It has no authority and is not persisted.
 * The panel being open or closed does not affect system behavior.
 */
export type AICommentaryPanelState = {
  /** Is the panel visible? (Default: false - HIDDEN by default) */
  readonly isVisible: boolean;

  /** Is commentary currently loading? */
  readonly isLoading: boolean;

  /** The commentary text (markdown, read-only) */
  readonly commentary: string | null;

  /** Error message if commentary failed to load */
  readonly error: string | null;

  /** Timestamp when commentary was last fetched */
  readonly lastFetchedAt: number | null;
};

/**
 * Initial state - panel is HIDDEN by default
 *
 * CRITICAL: The default state MUST be hidden.
 * AI commentary is opt-in only.
 */
export const INITIAL_AI_COMMENTARY_STATE: AICommentaryPanelState = {
  isVisible: false,
  isLoading: false,
  commentary: null,
  error: null,
  lastFetchedAt: null,
};

// ============================================================================
// STATE TRANSITIONS (PURE FUNCTIONS, NO SIDE EFFECTS)
// ============================================================================

/**
 * Open the AI commentary panel
 *
 * CRITICAL: This is an EXPLICIT user action.
 * The panel is NEVER opened automatically.
 */
export function openPanel(state: AICommentaryPanelState): AICommentaryPanelState {
  return {
    ...state,
    isVisible: true,
  };
}

/**
 * Close the AI commentary panel
 */
export function closePanel(state: AICommentaryPanelState): AICommentaryPanelState {
  return {
    ...state,
    isVisible: false,
  };
}

/**
 * Toggle the AI commentary panel visibility
 */
export function togglePanel(state: AICommentaryPanelState): AICommentaryPanelState {
  return {
    ...state,
    isVisible: !state.isVisible,
  };
}

/**
 * Set loading state (when fetching commentary)
 */
export function setLoading(state: AICommentaryPanelState): AICommentaryPanelState {
  return {
    ...state,
    isLoading: true,
    error: null,
  };
}

/**
 * Set commentary (after successful fetch)
 *
 * @param state - Current state
 * @param commentary - The commentary text (markdown)
 */
export function setCommentary(
  state: AICommentaryPanelState,
  commentary: string
): AICommentaryPanelState {
  return {
    ...state,
    isLoading: false,
    commentary,
    error: null,
    lastFetchedAt: Date.now(),
  };
}

/**
 * Set error (after failed fetch)
 *
 * @param state - Current state
 * @param error - The error message
 */
export function setError(
  state: AICommentaryPanelState,
  error: string
): AICommentaryPanelState {
  return {
    ...state,
    isLoading: false,
    commentary: null,
    error,
    lastFetchedAt: Date.now(),
  };
}

/**
 * Clear commentary (reset to initial state, but keep visibility)
 */
export function clearCommentary(state: AICommentaryPanelState): AICommentaryPanelState {
  return {
    ...state,
    isLoading: false,
    commentary: null,
    error: null,
    lastFetchedAt: null,
  };
}

